export function searchContent(query: string, limit = 8): ContentItem[] {
  const q = query.trim().toLowerCase().normalize("NFD").replace(/\p{M}/gu, "");
  if (!q) return [];

  const scored = contentIndex
    .map((item) => {
      const haystack = [item.title, item.category, ...item.keywords]
        .join(" ")
        .toLowerCase()
        .normalize("NFD")
        .replace(/\p{M}/gu, "");

      let score = 0;
      if (haystack.includes(q)) score += 10;
      if (item.title.toLowerCase().normalize("NFD").replace(/\p{M}/gu, "").includes(q)) {
        score += 20;
      }
      for (const part of q.split(/\s+/)) {
        if (part.length >= 2 && haystack.includes(part)) score += 3;
      }
      return { item, score };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((entry) => entry.item);
}
